// ─── Aggregate KPI Calculation ─────────────────────────────────────────────────
export function getAccountKPIs(days = 30) {
  const current = timeSeriesData.slice(-days);
  const previous = timeSeriesData.slice(-days * 2, -days);

  const sum = (arr: TimeSeriesPoint[], key: keyof TimeSeriesPoint) =>
    arr.reduce((acc, d) => acc + (d[key] as number), 0);

  const cSpend = sum(current, 'spend');
  const cPurchases = sum(current, 'purchases');
  const cRevenue = sum(current, 'revenue');
  const cImpressions = sum(current, 'impressions');
  const cClicks = sum(current, 'clicks');
  const cLPV = sum(current, 'landingPageViews');
  const cATC = sum(current, 'addToCart');
  const cIC = sum(current, 'initiateCheckout');
  const cReach = sum(current, 'reach');

  const pSpend = sum(previous, 'spend');
  const pPurchases = sum(previous, 'purchases');
  const pRevenue = sum(previous, 'revenue');
  const pImpressions = sum(previous, 'impressions');
  const pClicks = sum(previous, 'clicks');

  return {
    spend: { value: cSpend, previous: pSpend },
    purchases: { value: cPurchases, previous: pPurchases },
    revenue: { value: cRevenue, previous: pRevenue },
    roas: { value: cRevenue / cSpend, previous: pRevenue / pSpend },
    cpa: { value: cSpend / cPurchases, previous: pSpend / pPurchases },
    cpm: { value: (cSpend / cImpressions) * 1000, previous: (pSpend / pImpressions) * 1000 },
    ctr: { value: (cClicks / cImpressions) * 100, previous: (pClicks / pImpressions) * 100 },
    cpc: { value: cSpend / cClicks, previous: pSpend / pClicks },
    clicks: { value: cClicks, previous: pClicks },
    landingPageViews: { value: cLPV, previous: 0 },
    addToCart: { value: cATC, previous: 0 },
    initiateCheckout: { value: cIC, previous: 0 },
    costPerATC: { value: cSpend / cATC, previous: 0 },
    costPerCheckout: { value: cSpend / cIC, previous: 0 },
    frequency: { value: current.reduce((a, d) => a + d.frequency, 0) / current.length, previous: 0 },
    reach: { value: cReach, previous: 0 },
    impressions: { value: cImpressions, previous: pImpressions },
  };
}

export function getFunnelData(days = 30) {
  const recent = timeSeriesData.slice(-days);
  const sum = (key: keyof TimeSeriesPoint) => recent.reduce((a, d) => a + (d[key] as number), 0);

  const spend = sum('spend');
  const impressions = sum('impressions');
  const clicks = sum('clicks');
  const lpv = sum('landingPageViews');
  const atc = sum('addToCart');
  const ic = sum('initiateCheckout');
  const purchases = sum('purchases');

  return [
    { name: 'Impressions', value: impressions, cost: spend / impressions * 1000, conversionRate: 100, dropOff: 0 },
    { name: 'Link Clicks', value: clicks, cost: spend / clicks, conversionRate: (clicks / impressions) * 100, dropOff: 100 - (clicks / impressions) * 100 },
    { name: 'Landing Page Views', value: lpv, cost: spend / lpv, conversionRate: (lpv / clicks) * 100, dropOff: 100 - (lpv / clicks) * 100 },
    { name: 'Add to Cart', value: atc, cost: spend / atc, conversionRate: (atc / lpv) * 100, dropOff: 100 - (atc / lpv) * 100 },
    { name: 'Initiate Checkout', value: ic, cost: spend / ic, conversionRate: (ic / atc) * 100, dropOff: 100 - (ic / atc) * 100 },
    { name: 'Purchase', value: purchases, cost: spend / purchases, conversionRate: (purchases / ic) * 100, dropOff: 100 - (purchases / ic) * 100 },
  ];
}
