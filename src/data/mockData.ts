function randomBetween(min: number, max: number, decimals = 0): number {
  const val = Math.random() * (max - min) + min;
  return decimals > 0 ? parseFloat(val.toFixed(decimals)) : Math.round(val);
}

function jitter(base: number, pct = 0.15): number {
  return base * (1 + (Math.random() * 2 - 1) * pct);
}

// ─── Time Series (90 days) ────────────────────────────────────────────────────
export const timeSeriesData: TimeSeriesPoint[] = Array.from({ length: 90 }, (_, i) => {
  const date = format(subDays(today, 89 - i), 'yyyy-MM-dd');
  const weekday = new Date(date).getDay();
  const weekendMult = weekday === 0 || weekday === 6 ? 0.75 : 1;
  const trendMult = 0.85 + (i / 90) * 0.3;

  const impressions = Math.round(jitter(42000 * weekendMult * trendMult));
  const reach = Math.round(impressions * jitter(0.68));
  const clicks = Math.round(impressions * jitter(0.022));
  const landingPageViews = Math.round(clicks * jitter(0.82));
  const addToCart = Math.round(landingPageViews * jitter(0.16));
  const initiateCheckout = Math.round(addToCart * jitter(0.55));
  const purchases = Math.round(initiateCheckout * jitter(0.48));
  const revenue = purchases * jitter(68);
  const spend = revenue / jitter(2.85, 0.2);
  const frequency = parseFloat((impressions / reach).toFixed(2));

  return {
    date,
    spend: parseFloat(spend.toFixed(2)),
    purchases,
    revenue: parseFloat(revenue.toFixed(2)),
    roas: parseFloat((revenue / spend).toFixed(2)),
    cpa: parseFloat((spend / Math.max(purchases, 1)).toFixed(2)),
    ctr: parseFloat(((clicks / impressions) * 100).toFixed(2)),
    cpm: parseFloat(((spend / impressions) * 1000).toFixed(2)),
    cpc: parseFloat((spend / Math.max(clicks, 1)).toFixed(2)),
    frequency,
    impressions,
    clicks,
    landingPageViews,
    addToCart,
    initiateCheckout,
    reach,
  };
});

